import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { TRANSIT_FILES, TRANSIT_SOURCE_DIR } from "./transit-data-source.mjs";

const metadata = JSON.parse(await readFile(join(TRANSIT_SOURCE_DIR, TRANSIT_FILES.metadata), "utf8"));
if (!Array.isArray(metadata?.lines)) throw new Error("Add TPG line data first.");

const directions = Object.fromEntries(metadata.lines
  .map((line) => [String(line.number), [...new Set(line.directions.map((direction) => String(direction.headsign).trim()).filter(Boolean)), "Other"]])
  .sort(([a], [b]) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" })));

const source = `// Generated by scripts/build-shortcut-line-metadata.mjs.\nconst officialLineDirections = ${JSON.stringify(directions, null, 4)}\n`;
await writeFile("shortcut-line-metadata.cherri", source);
console.log(`Wrote ${Object.keys(directions).length} official lines.`);
