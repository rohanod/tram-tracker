import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { gzipSync, gunzipSync } from "node:zlib";

export const TRANSIT_SOURCE_DIR = "/Users/rohan/Documents/tpg-line-data/out-data";
export const TRANSIT_FILES = {
  metadata: "tpg-lines.info.json",
  geometry: "tpg-routes.polyline.json",
  stops: "tpg-stops.compact.json"
};

export async function buildTransitBundle() {
  const entries = await Promise.all(Object.entries(TRANSIT_FILES).map(async ([kind, name]) => {
    const path = join(TRANSIT_SOURCE_DIR, name);
    const bytes = await readFile(path);
    let value;
    try {
      value = JSON.parse(bytes.toString("utf8"));
    } catch {
      throw new Error(`Invalid transit JSON: ${path}`);
    }
    return [kind, { name, path, bytes, value }];
  }));
  const source = Object.fromEntries(entries);
  const metadata = compactMetadata(source.metadata.value);
  const geometry = validateGeometry(source.geometry.value, metadata);
  validateStops(source.stops.value);

  const hash = createHash("sha256");
  for (const kind of ["metadata", "geometry", "stops"]) {
    hash.update(source[kind].name).update("\0").update(source[kind].bytes).update("\0");
  }
  const version = hash.digest("hex");
  const payload = JSON.stringify({ version, metadata, geometry });
  const compressed = gzipSync(Buffer.from(payload), { level: 9, mtime: 0 });
  if (gunzipSync(compressed).toString("utf8") !== payload) throw new Error("Transit gzip roundtrip failed.");

  return {
    version,
    gzipBase64: compressed.toString("base64"),
    metadata,
    geometry,
    stops: source.stops.value,
    source
  };
}

export async function stageTransitData(stageRoot, { fullClientData }) {
  const bundle = await buildTransitBundle();
  const storageDir = join(stageRoot, "storage-data");
  await mkdir(storageDir, { recursive: true });
  if (fullClientData) {
    await Promise.all([
      copyFile(bundle.source.metadata.path, join(storageDir, TRANSIT_FILES.metadata)),
      copyFile(bundle.source.geometry.path, join(storageDir, TRANSIT_FILES.geometry))
    ]);
  } else {
    await Promise.all([
      writeFile(join(storageDir, TRANSIT_FILES.metadata), '{"generatedAt":"","lines":[]}'),
      writeFile(join(storageDir, TRANSIT_FILES.geometry), '{"v":1,"precision":5,"features":[]}')
    ]);
  }
  await copyFile(bundle.source.stops.path, join(storageDir, TRANSIT_FILES.stops));
  const serverGeneratedPath = join(stageRoot, "server", "transit-data.generated.ts");
  const clientGeneratedPath = join(stageRoot, "client", "transit-data.generated.ts");
  await Promise.all([
    mkdir(dirname(serverGeneratedPath), { recursive: true }),
    mkdir(dirname(clientGeneratedPath), { recursive: true })
  ]);
  await Promise.all([
    writeFile(serverGeneratedPath, serverGeneratedModule(bundle)),
    writeFile(clientGeneratedPath, clientGeneratedModule(bundle))
  ]);
  return bundle;
}

export function serverGeneratedModule(bundle) {
  return `// Generated by scripts/transit-data-source.mjs.\nexport const TRANSIT_DATA_VERSION = ${JSON.stringify(bundle.version)};\nexport const TRANSIT_DATA_GZIP_BASE64 = ${JSON.stringify(bundle.gzipBase64)};\n`;
}

export function clientGeneratedModule(bundle) {
  return `// Generated by scripts/transit-data-source.mjs.\nexport const TRANSIT_DATA_VERSION = ${JSON.stringify(bundle.version)};\n`;
}

function compactMetadata(value) {
  if (!Array.isArray(value?.lines) || !value.lines.length) throw new Error("Transit metadata has no lines.");
  const stops = new Map();
  const directionIds = new Set();
  const lines = value.lines.map((sourceLine) => {
    const line = canonicalLine(sourceLine?.number);
    if (!line) throw new Error("Transit metadata contains an invalid line.");
    const directions = (sourceLine.directions ?? []).map((sourceDirection) => {
      const id = String(sourceDirection?.id ?? "").trim();
      const headsign = String(sourceDirection?.headsign ?? sourceDirection?.to ?? "").trim();
      if (!id || !headsign || directionIds.has(id)) throw new Error(`Invalid or duplicate transit direction: ${id || "<missing>"}`);
      directionIds.add(id);
      const stopKeys = (sourceDirection.stops ?? []).map((sourceStop) => {
        const name = String(sourceStop?.name ?? "").trim();
        const lat = finiteCoordinate(sourceStop?.lat, -90, 90);
        const lon = finiteCoordinate(sourceStop?.lon, -180, 180);
        if (!name || lat === null || lon === null) throw new Error(`Invalid stop in direction ${id}.`);
        const key = `${name}|${lat.toFixed(5)}|${lon.toFixed(5)}`;
        if (!stops.has(key)) stops.set(key, { n: name, a: round5(lat), o: round5(lon) });
        return key;
      });
      if (!stopKeys.length) throw new Error(`Direction ${id} has no stops.`);
      return { i: id, h: headsign, f: String(sourceDirection?.from ?? "").trim(), s: stopKeys };
    });
    if (!directions.length) throw new Error(`Line ${line} has no directions.`);
    const color = normalizeColor(sourceLine?.colour ?? sourceLine?.color);
    return {
      l: line,
      c: color,
      f: validColor(sourceLine?.foreground) || foregroundFor(color),
      t: String(sourceLine?.vehicle ?? ""),
      d: directions
    };
  }).sort((a, b) => a.l.localeCompare(b.l, undefined, { numeric: true, sensitivity: "base" }));

  const stopKeys = [...stops.keys()];
  const stopIndexes = new Map(stopKeys.map((key, index) => [key, index]));
  for (const line of lines) for (const direction of line.d) direction.s = direction.s.map((key) => stopIndexes.get(key));
  return { v: 1, generatedAt: String(value.generatedAt ?? ""), stops: stopKeys.map((key) => stops.get(key)), lines };
}

function validateGeometry(value, metadata) {
  if (value?.v !== 1 || !Number.isInteger(value?.precision) || !Array.isArray(value?.features) || !value.features.length) {
    throw new Error("Invalid transit polyline geometry.");
  }
  const expected = new Set(metadata.lines.flatMap((line) => line.d.map((direction) => direction.i)));
  const seen = new Set();
  for (const feature of value.features) {
    const id = String(feature?.i ?? "").trim();
    if (!id || seen.has(id) || !expected.has(id) || !canonicalLine(feature?.l) || !Array.isArray(feature?.p) || !feature.p.length || feature.p.some((path) => typeof path !== "string" || !path)) {
      throw new Error(`Invalid geometry feature: ${id || "<missing>"}`);
    }
    seen.add(id);
  }
  if (seen.size !== expected.size) throw new Error(`Geometry does not match metadata: ${seen.size}/${expected.size} directions.`);
  return value;
}

function validateStops(value) {
  if (value?.v !== 1 || !Array.isArray(value?.s) || !value.s.length) throw new Error("Invalid compact stop index.");
  const ids = new Set();
  for (const stop of value.s) {
    const id = String(stop?.[0] ?? "").trim();
    const name = String(stop?.[2] ?? "").trim();
    const lat = finiteCoordinate(stop?.[3], -90, 90);
    const lon = finiteCoordinate(stop?.[4], -180, 180);
    if (!id || !name || lat === null || lon === null || ids.has(id)) throw new Error(`Invalid or duplicate compact stop: ${id || "<missing>"}`);
    ids.add(id);
  }
}

function canonicalLine(value) {
  const line = String(value ?? "").trim().toUpperCase();
  return /^\d+$/.test(line) ? String(Number(line)) : /^[A-Z0-9+]{1,8}$/.test(line) ? line : "";
}

function finiteCoordinate(value, min, max) {
  const number = Number(value);
  return Number.isFinite(number) && number >= min && number <= max ? number : null;
}

function round5(value) {
  return Math.round(value * 100000) / 100000;
}

function validColor(value) {
  const color = String(value ?? "").trim().toUpperCase();
  return /^#[0-9A-F]{6}$/.test(color) ? color : "";
}

function normalizeColor(value) {
  return validColor(value) || "#666666";
}

function foregroundFor(hex) {
  const values = [1, 3, 5].map((index) => Number.parseInt(hex.slice(index, index + 2), 16) / 255);
  const [red, green, blue] = values.map((value) => value <= 0.03928 ? value / 12.92 : Math.pow((value + 0.055) / 1.055, 2.4));
  return 0.2126 * red + 0.7152 * green + 0.0722 * blue > 0.45 ? "#111111" : "#FFFFFF";
}
